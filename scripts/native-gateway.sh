#!/usr/bin/env bash
# The OpenClaw gateway on the Mac itself, not in a container (RealityEngine_CI#592).
#
#   scripts/native-gateway.sh up [--agent-profile=NAME]   generate, migrate, start
#   scripts/native-gateway.sh down                        stop and unload
#   scripts/native-gateway.sh status                      what is running, and where
#   scripts/native-gateway.sh check                       preflight only, changes nothing
#   scripts/native-gateway.sh render                      write the LaunchAgent plist, load nothing
#
# It runs the host's own `openclaw` (npm -g), which must be the release this stack
# pins (OPENCLAW_VERSION), on a Node that release accepts, as a user LaunchAgent on
# 127.0.0.1. Containers reach it through host.docker.internal.
#
# Its home is OPENCLAW_NATIVE_HOME (default ~/.realityengine/openclaw), handed to
# OpenClaw as OPENCLAW_STATE_DIR. The user's own ~/.openclaw is never read or
# written. The home is generated by this stack's scripts, the same ones the
# container uses: harden-config.sh, sync-machine-agents.sh (the agents of the
# chosen profile), verify-openclaw-config.sh. migrate-state.sh runs first, so an
# upgrade of the host openclaw is migrated before the new gateway starts.
#
# Agents run sandboxed in Docker (sandbox.mode "all"). The sandbox image OpenClaw
# expects, openclaw-sandbox:bookworm-slim, is not in the npm package; it is built
# from docker/sandbox/Dockerfile, vendored from OpenClaw's source.
#
# The gateway token comes from .env when the gateway starts
# (scripts/native-gateway-run.sh); it is never written into the LaunchAgent.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

CYAN='\033[0;36m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
info() { echo -e "${CYAN}[native-gateway]${NC} $*"; }
ok()   { echo -e "${GREEN}[ok]${NC}   $*"; }
warn() { echo -e "${YELLOW}[warn]${NC}  $*"; }
die()  { echo -e "${RED}[error]${NC} $*" >&2; exit 1; }

CMD="${1:-}"; shift || true
AGENT_PROFILE="${OPENCLAW_AGENT_PROFILE:-regression}"
for arg in "$@"; do
  case "$arg" in
    --agent-profile=*) AGENT_PROFILE="${arg#*=}" ;;
    *) die "Unknown argument: $arg" ;;
  esac
done

if [[ -f .env ]]; then
  # The caller's environment wins over .env: native-gateway.sh passes the native
  # gateway's values (Ollama on loopback, its port), which .env sets for the
  # container. Sourcing .env alone overwrote them (2026-10-25).
  _caller_env="$(export -p)"
  # shellcheck source=/dev/null
  set -a; source .env; set +a
  eval "$_caller_env"
fi
PIN="${OPENCLAW_VERSION:-$(sed -n 's/^ARG OPENCLAW_VERSION=//p' Dockerfile.openclaw-gateway)}"
NATIVE_HOME="${OPENCLAW_NATIVE_HOME:-$HOME/.realityengine/openclaw}"
PORT="${OPENCLAW_GATEWAY_PORT:-18789}"
LABEL="${OPENCLAW_NATIVE_LABEL:-org.realityengine.openclaw-gateway}"
PLIST="${OPENCLAW_NATIVE_PLIST:-$HOME/Library/LaunchAgents/$LABEL.plist}"
LOG_DIR="$NATIVE_HOME/logs"
SANDBOX_IMAGE="openclaw-sandbox:bookworm-slim"
CDP_PORT="${RE_PORT_BROWSER_CDP:-9222}"
OLLAMA_URL="${OPENCLAW_NATIVE_OLLAMA_URL:-http://127.0.0.1:11434}"

# The openclaw the LaunchAgent will run, and the node it runs on. An explicit
# OPENCLAW_BIN wins; otherwise Homebrew's npm prefix, then PATH. Its node is the
# one beside it (npm -g installs into the node's own prefix), else PATH's.
resolve_bins() {
  OPENCLAW_BIN="${OPENCLAW_BIN:-}"
  if [[ -z "$OPENCLAW_BIN" ]]; then
    if [[ -x /opt/homebrew/bin/openclaw ]]; then OPENCLAW_BIN=/opt/homebrew/bin/openclaw
    else OPENCLAW_BIN="$(command -v openclaw || true)"; fi
  fi
  [[ -n "$OPENCLAW_BIN" && -x "$OPENCLAW_BIN" ]] || \
    die "openclaw is not installed: npm install -g openclaw@$PIN, on the Node it requires (${OPENCLAW_NODE_EXACT:-see its engines field})"
  NODE_BIN="${OPENCLAW_NODE:-}"
  if [[ -z "$NODE_BIN" ]]; then
    if [[ -x "$(dirname "$OPENCLAW_BIN")/node" ]]; then NODE_BIN="$(dirname "$OPENCLAW_BIN")/node"
    else NODE_BIN="$(command -v node || true)"; fi
  fi
  [[ -n "$NODE_BIN" && -x "$NODE_BIN" ]] || die "no node found for $OPENCLAW_BIN"
  BIN_PATH="$(dirname "$NODE_BIN"):$(dirname "$OPENCLAW_BIN"):/usr/bin:/bin:/usr/sbin:/sbin"
  # Docker for the sandboxes. Docker Desktop's CLI is a symlink in one of these.
  for d in /usr/local/bin /opt/homebrew/bin "$HOME/.docker/bin"; do
    [[ -x "$d/docker" ]] && BIN_PATH="$BIN_PATH:$d"
  done
}

preflight() {
  resolve_bins
  local version node_version engines
  version="$(env PATH="$BIN_PATH" "$OPENCLAW_BIN" --version 2>/dev/null | awk '{print $2}')"
  [[ "$version" == "$PIN" ]] || \
    die "the host openclaw is ${version:-unknown}, this stack pins $PIN: PATH=$(dirname "$NODE_BIN"):\$PATH npm install -g openclaw@$PIN"
  node_version="$("$NODE_BIN" --version | sed 's/^v//')"
  # The package's own engines field: the bin is a symlink to <package>/openclaw.mjs.
  engines="$("$NODE_BIN" -e '
    const fs = require("fs"), path = require("path");
    const dir = path.dirname(fs.realpathSync(process.argv[1]));
    const p = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    process.stdout.write((p.engines && p.engines.node) || "");' "$OPENCLAW_BIN")"
  # A plain range check (">=a <b || >=c"), which is all OpenClaw's engines field uses.
  "$NODE_BIN" -e '
    const [v, range] = process.argv.slice(1);
    const n = s => s.split(".").map(Number);
    const cmp = (a, b) => { for (let i = 0; i < 3; i++) { if ((a[i]||0) !== (b[i]||0)) return (a[i]||0) - (b[i]||0); } return 0; };
    const ok = !range || range.split("||").some(alt => alt.trim().split(/\s+/).filter(Boolean).every(c => {
      const m = c.match(/^(>=|<=|>|<|=)?v?([\d.]+)$/); if (!m) return false;
      const d = cmp(n(v), n(m[2]));
      return { ">=": d >= 0, "<=": d <= 0, ">": d > 0, "<": d < 0, "=": d === 0, undefined: d === 0 }[m[1]];
    }));
    process.exit(ok ? 0 : 1);' "$node_version" "$engines" || \
    die "openclaw $version needs Node $engines; $NODE_BIN is $node_version"
  if [[ -n "${OPENCLAW_NODE_EXACT:-}" && "$node_version" != "$OPENCLAW_NODE_EXACT" ]]; then
    die "the release names Node $OPENCLAW_NODE_EXACT; $NODE_BIN is $node_version"
  fi
  ok "openclaw $version on Node $node_version ($NODE_BIN)"
  docker info >/dev/null 2>&1 || die "Docker is not answering; the agent sandboxes need it"
  curl -sf -m 5 "$OLLAMA_URL/api/version" >/dev/null || warn "Ollama does not answer at $OLLAMA_URL"
}

loaded() { launchctl print "gui/$(id -u)/$LABEL" >/dev/null 2>&1; }

unload() {
  if loaded; then
    launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
    for _ in $(seq 1 20); do loaded || break; sleep 1; done
  fi
}

write_plist() {
  mkdir -p "$(dirname "$PLIST")" "$LOG_DIR"
  cat > "$PLIST" <<PLIST_XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>$ROOT_DIR/scripts/native-gateway-run.sh</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>$BIN_PATH</string>
    <key>HOME</key><string>$HOME</string>
    <key>OPENCLAW_BIN</key><string>$OPENCLAW_BIN</string>
    <key>OPENCLAW_STATE_DIR</key><string>$NATIVE_HOME</string>
    <key>OPENCLAW_GATEWAY_PORT</key><string>$PORT</string>
    <key>OLLAMA_BASE_URL</key><string>$OLLAMA_URL</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>StandardOutPath</key><string>$LOG_DIR/gateway.log</string>
  <key>StandardErrorPath</key><string>$LOG_DIR/gateway.log</string>
</dict>
</plist>
PLIST_XML
  chmod 600 "$PLIST"
  plutil -lint "$PLIST" >/dev/null || die "generated $PLIST is not a valid plist"
}

ensure_sandbox_image() {
  if docker image inspect "$SANDBOX_IMAGE" >/dev/null 2>&1; then
    ok "sandbox image $SANDBOX_IMAGE present"
  else
    info "building $SANDBOX_IMAGE (docker/sandbox/Dockerfile)"
    docker build -q -t "$SANDBOX_IMAGE" -f docker/sandbox/Dockerfile docker/sandbox </dev/null >/dev/null
    ok "built $SANDBOX_IMAGE"
  fi
}

generate() {
  local index
  index="$("$ROOT_DIR/scripts/agent-profile.sh" "$AGENT_PROFILE")"
  info "agent profile: $AGENT_PROFILE ($(jq -r '.total' "$index") machine agents)"
  mkdir -p "$NATIVE_HOME"; chmod 700 "$NATIVE_HOME"
  local cdp=""
  if curl -sf -m 3 "http://127.0.0.1:$CDP_PORT/json/version" >/dev/null 2>&1; then
    cdp="http://127.0.0.1:$CDP_PORT"
  else
    warn "no browser sidecar answers on 127.0.0.1:$CDP_PORT; the gateway gets no browser profile"
  fi
  local -a envs=(OPENCLAW_STATE_DIR="$NATIVE_HOME" OPENCLAW_HOME_DIR="$NATIVE_HOME"
                 OPENCLAW_SCHEMA=entries OPENCLAW_GATEWAY_BIND=loopback OPENCLAW_GATEWAY_PORT="$PORT"
                 OLLAMA_BASE_URL="$OLLAMA_URL" OPENCLAW_BROWSER_CDP_URL="$cdp"
                 OPENCLAW_AGENT_PROFILE="$AGENT_PROFILE" OPENCLAW_AGENT_INDEX_PATH="$index")
  env PATH="$BIN_PATH:$PATH" "${envs[@]}" "$ROOT_DIR/scripts/migrate-state.sh"
  env "${envs[@]}" "$ROOT_DIR/scripts/harden-config.sh"
  env "${envs[@]}" "$ROOT_DIR/scripts/sync-machine-agents.sh"
  env "${envs[@]}" "$ROOT_DIR/scripts/verify-openclaw-config.sh"
  # The native values, not the container's: .env sets those for the container, and
  # a generator that read them instead pointed the gateway at host.docker.internal.
  jq -e --arg ollama "$OLLAMA_URL" --argjson port "$PORT" '
    .gateway.bind == "loopback" and .gateway.port == $port and
    .models.providers.ollama.baseUrl == $ollama' "$NATIVE_HOME/openclaw.json" >/dev/null || \
    die "the generated config does not bind loopback:$PORT with Ollama at $OLLAMA_URL: $(jq -c '{bind: .gateway.bind, port: .gateway.port, ollama: .models.providers.ollama.baseUrl}' "$NATIVE_HOME/openclaw.json")"
  ok "config binds 127.0.0.1:$PORT and uses Ollama at $OLLAMA_URL"
  # What this deployment loaded, for verify-deployment.sh and the corpus check.
  mkdir -p "$ROOT_DIR/machine-behaviors/agents/.generated"
  cp "$index" "$ROOT_DIR/machine-behaviors/agents/.generated/INDEX.deployed.json"
  EXPECTED_IDS="$(jq -r '.agents[].agentId' "$index")"
}

wait_ready() {
  local token code ids missing=""
  for _ in $(seq 1 60); do
    curl -sf -m 3 "http://127.0.0.1:$PORT/healthz" >/dev/null 2>&1 && break
    sleep 2
  done
  curl -sf -m 3 "http://127.0.0.1:$PORT/healthz" >/dev/null 2>&1 || \
    die "the gateway did not answer /healthz on 127.0.0.1:$PORT; see $LOG_DIR/gateway.log"
  ok "gateway answers on 127.0.0.1:$PORT"
  token="$(sed -n 's/^OPENCLAW_GATEWAY_TOKEN=//p' .env | tail -1 | tr -d "\"'")"
  code="$(curl -s -m 5 -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/v1/models")"
  [[ "$code" == 401 ]] || die "/v1/models without the token returned $code, expected 401"
  ids="$(curl -sf -m 10 -H "Authorization: Bearer $token" "http://127.0.0.1:$PORT/v1/models" | jq -r '.data[].id')" || \
    die "/v1/models with the token failed"
  while IFS= read -r id; do
    [[ -n "$id" ]] || continue
    grep -qxF "openclaw/$id" <<<"$ids" || missing="$missing $id"
  done <<<"$EXPECTED_IDS"
  [[ -z "$missing" ]] || die "the gateway does not list these agents:$missing"
  ok "the gateway lists every agent of the profile ($(grep -c . <<<"$EXPECTED_IDS")), and refuses a call without the token"
}

case "$CMD" in
  check)
    preflight ;;
  render)
    resolve_bins
    write_plist
    echo "$PLIST" ;;
  up)
    preflight
    if lsof -nP -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1 && ! loaded; then
      die "port $PORT is held by another process ($(lsof -nP -iTCP:"$PORT" -sTCP:LISTEN | awk 'NR==2{print $1" pid "$2}')); stop it first (the container gateway: docker compose stop openclaw-gateway)"
    fi
    unload
    generate
    ensure_sandbox_image
    write_plist
    launchctl bootstrap "gui/$(id -u)" "$PLIST"
    wait_ready
    ok "native OpenClaw gateway up: LaunchAgent $LABEL, home $NATIVE_HOME, log $LOG_DIR/gateway.log" ;;
  down)
    unload
    # The agents' sandbox containers idle until removed; take only this home's.
    removed=0
    for c in $(docker ps -aq --filter name=openclaw-sbx 2>/dev/null); do
      if docker inspect -f '{{range .Mounts}}{{.Source}} {{end}}' "$c" 2>/dev/null | grep -qF "$NATIVE_HOME/"; then
        docker rm -f "$c" >/dev/null 2>&1 && removed=$((removed + 1))
      fi
    done
    ok "native OpenClaw gateway stopped ($LABEL); removed $removed sandbox container(s)" ;;
  status)
    resolve_bins
    echo "label:   $LABEL ($(loaded && echo loaded || echo 'not loaded'))"
    echo "home:    $NATIVE_HOME"
    echo "binary:  $OPENCLAW_BIN ($(env PATH="$BIN_PATH" "$OPENCLAW_BIN" --version 2>/dev/null)), node $("$NODE_BIN" --version)"
    echo "healthz: $(curl -s -m 3 -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/healthz")"
    echo "log:     $LOG_DIR/gateway.log" ;;
  *)
    sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
